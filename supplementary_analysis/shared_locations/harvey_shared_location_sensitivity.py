"""Validate and summarize Harvey fixed shared-location sensitivity tables.

    python harvey_shared_location_sensitivity.py --tables shared_tables --output results

Starts from six existing observed-data aggregate tables, either supplied by
the original analysis or generated by harvey_shared_location_construction.py.
Recalculates baseline changes, recovery means and the added-location HSR
accounting; checks duplicate exports before plotting SI Figures S9–S11.
No raw records, confidence intervals or simulated data are generated.
"""
from pathlib import Path
import argparse
import hashlib
import json
import numpy as np
import pandas as pd


def analyze(input_dir, output_dir):
    INPUT = input_dir
    TABLE = output_dir
    TABLE.mkdir(parents=True, exist_ok=True)
    FILES = [
        "comment7_fixed_definition_weekly_metrics.csv",
        "comment7_fixed_definition_phase_summary.csv",
        "comment7_fixed_definition_location_comparison.csv",
        "comment7_fixed_period_definition_weekly.csv",
        "comment7_fixed_period_definition_overlap.csv",
        "comment7_fixed_period_definition_coverage.csv",
    ]
    data = {name: pd.read_csv(INPUT / name) for name in FILES}
    manifest = pd.DataFrame([
        {"file": name, "sha256": hashlib.sha256((INPUT / name).read_bytes()).hexdigest(),
         "rows": len(data[name])} for name in FILES
    ])
    manifest.to_csv(TABLE / "input_manifest.csv", index=False)

    W = data[FILES[0]].copy()
    ACUTE = "Fixed weeks 7--8"
    EXTENDED = "Fixed full displacement"  # Source label; actual bound is September 28.
    KS = [1, 3, 5, 10]
    KEYS = ["definition", "threshold", "week"]
    METRICS = ["host_dwell_shared", "host_dwell_nonshared", "encounter_index", "host_shared_ratio"]
    assert not W.duplicated(KEYS).any(), "Duplicate result keys."
    assert len(W) == 144 and W.definition.nunique() == 3
    assert np.isfinite(W[METRICS].to_numpy()).all(), "Non-finite source metrics."
    assert W.host_shared_ratio.between(0, 1).all()
    checks = []

    def check(label, error, tolerance=1e-9):
        checks.append({"check": label, "max_absolute_error": float(error),
                       "tolerance": tolerance, "passed": bool(error <= tolerance)})
        if error > tolerance:
            raise ValueError(f"{label}: {error} exceeds {tolerance}")

    for key, group in W.groupby(["definition", "threshold"]):
        assert set(group.week) == set(range(12)), f"Incomplete weekly series: {key}"
    for metric in METRICS:
        baseline = W.loc[W.week.between(0, 5)].groupby(["definition", "threshold"])[metric].mean()
        ix = pd.MultiIndex.from_frame(W[["definition", "threshold"]])
        b = baseline.reindex(ix).to_numpy()
        assert (b > 0).all()
        expected = 100 * (W[metric].to_numpy() / b - 1)
        check(f"{metric}: saved percentage versus recalculation",
              np.max(np.abs(expected - W[f"change_{metric}_pct"].to_numpy())))

    other = data[FILES[3]].rename(columns={
        "mean_dwell_shared": "host_dwell_shared", "mean_dwell_nonshared": "host_dwell_nonshared"})
    joined = W.merge(other, on=KEYS, suffixes=("_a", "_b"), validate="one_to_one")
    assert len(joined) == 96
    for metric in METRICS:
        check(f"Two weekly exports: {metric}",
              np.max(np.abs(joined[f"{metric}_a"] - joined[f"{metric}_b"])))

    W["period"] = np.select([W.week.between(0, 5), W.week.eq(6),
                              W.week.isin([7, 8]), W.week.isin([9, 10, 11])],
                             ["baseline", "week 6", "weeks 7--8", "weeks 9--11"], default="invalid")
    pctcols = [f"change_{m}_pct" for m in METRICS]
    phase = W.groupby(["definition", "threshold", "period"], as_index=False)[METRICS + pctcols].mean()
    phase_join = phase.merge(data[FILES[1]], on=["definition", "threshold", "period"],
                             suffixes=("_new", "_saved"), validate="one_to_one")
    assert len(phase_join) == 24
    for column in pctcols:
        check(f"Phase means: {column}",
              np.max(np.abs(phase_join[column + "_new"] - phase_join[column + "_saved"])))

    O = data[FILES[4]].copy()
    assert set(O.threshold) == set(KS)
    assert (O.acute_only == 0).all() and (O.intersection == O.acute_shared_pois).all()
    check("POI set cardinalities", np.max(np.abs(O.full_displacement_shared_pois - O.intersection - O.full_only)))
    check("POI Jaccard", np.max(np.abs(O.jaccard - O.intersection / (O.acute_shared_pois + O.full_displacement_shared_pois - O.intersection))))
    O["increase_relative_to_acute_pct"] = 100 * O.full_only / O.acute_shared_pois
    O["added_share_of_extended_pct"] = 100 * O.full_only / O.full_displacement_shared_pois
    locations = data[FILES[2]].query("comparison == 'weeks 7--8 vs full'").set_index("threshold")
    for new, old in [("acute_shared_pois", "locations_a"), ("full_displacement_shared_pois", "locations_b"),
                     ("intersection", "intersection"), ("full_only", "only_b"), ("jaccard", "jaccard")]:
        check(f"Two overlap exports: {new}", np.max(np.abs(O.set_index("threshold")[new] - locations[old])))

    # Exact HSR decomposition. The extended shared set contains the acute set.
    # Added-share_t = HSR_extended_t - HSR_acute_t, with the same weekly host denominator.
    parts = []
    for k in KS:
        a = W.loc[(W.definition == ACUTE) & (W.threshold == k)].set_index("week").sort_index()
        f = W.loc[(W.definition == EXTENDED) & (W.threshold == k)].set_index("week").sort_index()
        added = f.host_shared_ratio - a.host_shared_ratio
        assert added.min() >= -1e-12
        ba = a.host_shared_ratio.loc[0:5].mean()
        bn = added.loc[0:5].mean()
        bf = f.host_shared_ratio.loc[0:5].mean()
        ca = 100 * (a.host_shared_ratio / ba - 1)
        cn = 100 * (added / bn - 1)
        cf = 100 * (f.host_shared_ratio / bf - 1)
        reconstructed = (ba / bf) * ca + (bn / bf) * cn
        check(f"Exact added-POI HSR decomposition, k={k}", (cf - reconstructed).abs().max())
        parts.append(pd.DataFrame({"threshold": k, "week": a.index,
            "acute_host_share": a.host_shared_ratio.to_numpy(),
            "extended_host_share": f.host_shared_ratio.to_numpy(),
            "added_poi_host_share": added.to_numpy(),
            "added_share_baseline": bn, "acute_share_baseline": ba,
            "extended_share_baseline": bf,
            "acute_change_pct": ca.to_numpy(), "added_change_pct": cn.to_numpy(),
            "extended_change_pct": cf.to_numpy(),
            "acute_component_pp": ((ba / bf) * ca).to_numpy(),
            "added_component_pp": ((bn / bf) * cn).to_numpy()}))
    decomp = pd.concat(parts, ignore_index=True)


    coverage = data[FILES[5]]
    if len(coverage) != 1:
        raise ValueError("Expected one reference-period coverage record")
    start = pd.to_datetime(coverage.observed_start).iloc[0]
    end = pd.to_datetime(coverage.observed_end).iloc[0]
    if start > pd.Timestamp("2017-08-25") or end < pd.Timestamp("2017-09-28"):
        raise ValueError("Extended reference lacks full observed Aug25–Sep28 coverage")
    phase.to_csv(TABLE / "verified_phase_summary.csv", index=False)
    O.to_csv(TABLE / "verified_location_overlap.csv", index=False)
    decomp.to_csv(TABLE / "host_shared_ratio_added_poi_decomposition.csv", index=False)
    pd.DataFrame(checks).to_csv(TABLE / "numeric_checks.csv", index=False)
    recovery = phase.loc[phase.period.eq("weeks 9--11") & phase.definition.isin([ACUTE, EXTENDED])].copy()
    recovery.to_csv(TABLE / "recovery_summary.csv", index=False)
    recovery.loc[recovery.threshold.eq(3)].to_csv(TABLE / "reference_period_k3_summary.csv", index=False)
    return W, recovery, O, checks


def make_figures(weekly, output):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import matplotlib.dates as mdates
    acute = "Fixed weeks 7--8"
    extended = "Fixed full displacement"
    thresholds = [1, 3, 5, 10]
    weekly = weekly.copy()
    weekly["date"] = pd.Timestamp("2017-07-07") + pd.to_timedelta(7 * weekly.week, unit="D")
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 9,
                         "axes.linewidth": .8, "pdf.fonttype": 42, "savefig.facecolor": "white"})
    ticks = pd.to_datetime(["2017-07-07", "2017-08-04", "2017-09-01", "2017-09-22"])
    def style(ax):
        ax.axhline(0, color=".5", linewidth=.8)
        ax.axvspan(pd.Timestamp("2017-08-25"), pd.Timestamp("2017-09-08"), color="#F3D36A", alpha=.24, linewidth=0)
        ax.set_xticks(ticks)
        ax.xaxis.set_major_formatter(mdates.DateFormatter("%b %d"))
        ax.tick_params(axis="x", rotation=35)
        ax.set_ylabel("Change from baseline (%)")
    def save(fig, name):
        fig.tight_layout()
        for suffix in ["png", "pdf"]:
            fig.savefig(output / f"{name}.{suffix}", dpi=300, bbox_inches="tight")
        plt.close(fig)
    # S9: identical weekly host activity, fixed profiles built under two windows.
    fig, axes = plt.subplots(2, 1, figsize=(7.1, 5.7), sharex=True)
    for ax, metric, title in zip(axes, ["encounter_index", "host_shared_ratio"], ["Encounter Index", "Host Shared Ratio"]):
        style(ax)
        for definition, label, color, marker in [(acute, "Aug 25–Sep 7", "#2A7F62", "o"), (extended, "Aug 25–Sep 28", "#D46A28", "s")]:
            q = weekly.loc[weekly.definition.eq(definition) & weekly.threshold.eq(3)].sort_values("week")
            ax.plot(q.date, q[f"change_{metric}_pct"], label=label, color=color, marker=marker, markersize=4)
        ax.set_title(title)
    axes[0].legend(frameon=False)
    save(fig, "comment6_fixed_acute_vs_extended_threshold3")
    # S10: per-active-POI dwell, each group's own six-week baseline.
    fig, axes = plt.subplots(1, 4, figsize=(13.6, 3.8), sharey=True)
    for ax, threshold in zip(axes, thresholds):
        style(ax)
        q = weekly.loc[weekly.definition.eq(acute) & weekly.threshold.eq(threshold)].sort_values("week")
        for metric, label, color in [("host_dwell_shared", "Shared", "#D55E00"), ("host_dwell_nonshared", "Below threshold", "#0072B2")]:
            ax.plot(q.date, q[f"change_{metric}_pct"], color=color, marker="o", markersize=3, label=label)
        ax.set_title(f"At least {threshold} distinct evacuees")
        if ax is not axes[0]:
            ax.set_ylabel("")
    axes[0].legend(frameon=False, fontsize=8)
    fig.suptitle("Host dwell time per active POI")
    save(fig, "c7_rechecked_dwell_weeks78")
    # S11: threshold-specific restricted and renormalized evacuee profiles.
    fig, axes = plt.subplots(2, 1, figsize=(7.1, 5.7), sharex=True)
    colors = ["#1B9E77", "#D95F02", "#7570B3", "#E7298A"]
    for ax, metric, title in zip(axes, ["encounter_index", "host_shared_ratio"], ["Encounter Index", "Host Shared Ratio"]):
        style(ax)
        for threshold, color in zip(thresholds, colors):
            q = weekly.loc[weekly.definition.eq(acute) & weekly.threshold.eq(threshold)].sort_values("week")
            ax.plot(q.date, q[f"change_{metric}_pct"], marker="o", markersize=3,
                    color=color, label=f"At least {threshold}")
        ax.set_title(title)
    axes[0].legend(frameon=False, ncol=2, fontsize=8)
    save(fig, "c7_rechecked_indicators_weeks78")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--tables", required=True, type=Path, help="Directory with six comment7 fixed-definition CSVs")
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--no-figures", action="store_true")
    args = parser.parse_args()
    weekly, recovery, overlap, checks = analyze(args.tables, args.output)
    if not args.no_figures:
        make_figures(weekly, args.output)
    summary = dict(input_stage="Saved aggregate tables; raw processing not rerun", main_threshold=3,
                   reference_periods=["2017-08-25/2017-09-07", "2017-08-25/2017-09-28"],
                   baseline_weeks=list(range(6)), recovery_weeks=[9, 10, 11],
                   numeric_checks=len(checks), all_checks_passed=all(q["passed"] for q in checks),
                   max_numeric_error=max(q["max_absolute_error"] for q in checks),
                   weekly_rows=len(weekly), recovery_rows=len(recovery))
    (args.output / "analysis_summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(f"Verified {len(checks)} aggregate checks; saved summaries to {args.output}")


if __name__ == "__main__":
    main()
